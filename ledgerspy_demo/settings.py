"""Demo settings, read from the environment only. No secret has a default or appears in source code.

- `LEDGERSPY_MODE` (required, `demo`): anything else, or unset, means the normal offline application; demo
  settings refuse to load.
- `LEDGERSPY_DEMO_SESSION_KEY` (required, secret): HMAC key for workspace cookies, at least 32 random
  characters, generated by the operator and kept in the host's secret store.
- `LEDGERSPY_DEMO_DATA_DIR` (required): absolute path of the local, ephemeral folder of visitor workspaces.
- `LEDGERSPY_DEMO_PUBLIC_ORIGIN` (required): the one public origin, e.g. `https://<service>.onrender.com`
  (http only for loopback testing).
- `LEDGERSPY_DEMO_STORAGE_URL`, `_BUCKET`, `_SERVICE_KEY` (all or none; the key is secret): the private
  Supabase Storage bucket for snapshots. None means an ephemeral demo without persistence.
- `LEDGERSPY_DEMO_<LIMIT>` (optional): overrides of `DemoLimits`, stricter than offline only.
- `LEDGERSPY_DEMO_TRUSTED_PROXY_HOPS` (optional, default 0): how many reverse proxies in front of the
  service append to `X-Forwarded-For`. 0 = forwarded headers are ignored and the TCP peer is the client key.
  Set it only when the platform guarantees those proxies (entries left of them are client-controlled).
- `LEDGERSPY_DEMO_BIND_HOST` (optional, default `127.0.0.1`): `0.0.0.0` must be set explicitly to listen
  publicly.
- `LEDGERSPY_DEMO_PORT`, else `PORT` (set by the host platform), else 10000.
- `LEDGERSPY_DEMO_SEED_DIR` (optional): an absolute path to a synthetic seed built ahead of time
  (`python -m ledgerspy_demo.prebuild <dir>`, e.g. in the container image); it is verified at start-up and
  only read. Without it, the seed is built in the data folder at start-up.
"""

import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import PurePosixPath, PureWindowsPath
from urllib.parse import urlsplit

from ledgerspy_demo.datadir import check_data_dir_setting
from ledgerspy_demo.limits import DemoConfigError, DemoLimits

MIN_KEY_CHARS = 32
_BUCKET = re.compile(r"^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$")
_LOOPBACK = {"127.0.0.1", "localhost"}


def _required(env: Mapping[str, str], name: str) -> str:
    v = (env.get(name) or "").strip()
    if not v:
        raise DemoConfigError(f"{name} is required in demo mode")
    return v


def _origin(value: str) -> str:
    parts = urlsplit(value)
    if parts.path not in ("", "/") or parts.query or parts.fragment or parts.username or parts.password:
        raise DemoConfigError("LEDGERSPY_DEMO_PUBLIC_ORIGIN must be a bare origin (scheme://host[:port])")
    host = (parts.hostname or "").lower()
    if not host:
        raise DemoConfigError("LEDGERSPY_DEMO_PUBLIC_ORIGIN has no host")
    if parts.scheme == "http" and host not in _LOOPBACK:
        raise DemoConfigError(
            "a public demo origin must use https (http is allowed for loopback testing only)"
        )
    if parts.scheme not in ("http", "https"):
        raise DemoConfigError("LEDGERSPY_DEMO_PUBLIC_ORIGIN must be http(s)")
    return f"{parts.scheme}://{parts.netloc.lower()}"


@dataclass(frozen=True)
class StorageSettings:
    url: str
    bucket: str
    service_key: str = field(repr=False)  # secret: never printed

    def __repr__(self) -> str:
        return f"StorageSettings(url={self.url!r}, bucket={self.bucket!r}, service_key=<redacted>)"


@dataclass(frozen=True)
class DemoSettings:
    session_key: bytes = field(repr=False)
    data_dir: str
    public_origin: str
    limits: DemoLimits
    storage: StorageSettings | None  # None: ephemeral demo, no snapshots
    trusted_proxy_hops: int = 0
    bind_host: str = "127.0.0.1"
    port: int = 10000
    seed_dir: str | None = None

    def __repr__(self) -> str:
        return (
            f"DemoSettings(session_key=<redacted>, data_dir={self.data_dir!r}, public_origin="
            f"{self.public_origin!r}, limits={self.limits!r}, storage={self.storage!r}, trusted_proxy_hops="
            f"{self.trusted_proxy_hops}, bind_host={self.bind_host!r}, port={self.port})"
        )

    @property
    def persistent(self) -> bool:
        return self.storage is not None

    @property
    def public_host(self) -> str:
        """The exact Host header the service accepts (host[:port] of the public origin)."""
        return self.public_origin.split("://", 1)[1]

    @classmethod
    def from_env(cls, env: Mapping[str, str]) -> "DemoSettings":
        if (env.get("LEDGERSPY_MODE") or "").strip() != "demo":
            raise DemoConfigError(
                "demo mode is not enabled (LEDGERSPY_MODE=demo); the offline application applies"
            )
        key = _required(env, "LEDGERSPY_DEMO_SESSION_KEY")
        if len(key) < MIN_KEY_CHARS or key.strip() != key or len(set(key)) < 8:
            raise DemoConfigError(
                f"LEDGERSPY_DEMO_SESSION_KEY must be at least {MIN_KEY_CHARS} random characters"
            )
        data_dir = _required(env, "LEDGERSPY_DEMO_DATA_DIR")
        check_data_dir_setting(data_dir)  # absolute, no '..', not a root, UNC or system folder
        origin = _origin(_required(env, "LEDGERSPY_DEMO_PUBLIC_ORIGIN"))
        names = (
            "LEDGERSPY_DEMO_STORAGE_URL",
            "LEDGERSPY_DEMO_STORAGE_BUCKET",
            "LEDGERSPY_DEMO_STORAGE_SERVICE_KEY",
        )
        given = [bool((env.get(n) or "").strip()) for n in names]
        storage = None
        if any(given):
            if not all(given):
                raise DemoConfigError(
                    f"set all of {', '.join(names)} for snapshots, or none for an ephemeral demo"
                )
            url = (env.get(names[0]) or "").strip()
            parts = urlsplit(url)
            if parts.scheme != "https" or not parts.hostname or parts.path not in ("", "/"):
                raise DemoConfigError("LEDGERSPY_DEMO_STORAGE_URL must be an https origin")
            bucket = (env.get(names[1]) or "").strip()
            if not _BUCKET.match(bucket):
                raise DemoConfigError("LEDGERSPY_DEMO_STORAGE_BUCKET is not a valid bucket name")
            service_key = (env.get(names[2]) or "").strip()
            if len(service_key) < 20 or any(c.isspace() for c in service_key):
                raise DemoConfigError("LEDGERSPY_DEMO_STORAGE_SERVICE_KEY does not look like a service key")
            if service_key.startswith(
                ("sb_publishable_", "sb_anon_")
            ):  # a browser key cannot use a private bucket
                raise DemoConfigError(
                    "LEDGERSPY_DEMO_STORAGE_SERVICE_KEY is a publishable key; use the project's secret key"
                )
            storage = StorageSettings(
                url=f"https://{parts.netloc.lower()}", bucket=bucket, service_key=service_key
            )
        hops_text = (env.get("LEDGERSPY_DEMO_TRUSTED_PROXY_HOPS") or "0").strip()
        if not hops_text.isdigit() or int(hops_text) > 3:
            raise DemoConfigError("LEDGERSPY_DEMO_TRUSTED_PROXY_HOPS must be an integer from 0 to 3")
        bind = (env.get("LEDGERSPY_DEMO_BIND_HOST") or "127.0.0.1").strip()
        if bind not in ("127.0.0.1", "0.0.0.0"):  # noqa: S104 — public binding only when set explicitly
            raise DemoConfigError("LEDGERSPY_DEMO_BIND_HOST must be 127.0.0.1 or 0.0.0.0")
        port_text = (env.get("LEDGERSPY_DEMO_PORT") or env.get("PORT") or "10000").strip()
        if not port_text.isdigit() or not 1 <= int(port_text) <= 65535:
            raise DemoConfigError("the demo port must be an integer from 1 to 65535")
        seed_dir = (env.get("LEDGERSPY_DEMO_SEED_DIR") or "").strip() or None
        if seed_dir is not None and not (
            PurePosixPath(seed_dir).is_absolute() or PureWindowsPath(seed_dir).is_absolute()
        ):
            raise DemoConfigError("LEDGERSPY_DEMO_SEED_DIR must be an absolute path")
        return cls(
            seed_dir=seed_dir,
            session_key=key.encode("utf-8"),
            data_dir=data_dir,
            public_origin=origin,
            limits=DemoLimits.from_env(env),
            storage=storage,
            trusted_proxy_hops=int(hops_text),
            bind_host=bind,
            port=int(port_text),
        )
