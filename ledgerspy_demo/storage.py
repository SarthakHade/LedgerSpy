"""Server-side client for a PRIVATE Supabase Storage bucket (snapshots of visitor workspaces).

- Authenticated with the service key from the environment (`LEDGERSPY_DEMO_STORAGE_SERVICE_KEY`); the key is
  sent only to the configured https origin, never logged, never in an error message or a response.
- Every object key is checked against `OBJECT_KEY` before a request is made: keys are generated by the server
  from validated workspace IDs and are always inside `workspaces/<W-id>/`.
- Bounded: a timeout on every request, a few retries for timeouts and 5xx answers only (never for 4xx), and a
  cap on every response body (a larger answer is refused while it is read).
- The transport is injectable (`Transport`), so tests use an in-memory fake and never real credentials.

Endpoints (Supabase Storage REST API, as used by supabase/storage-js): upload `POST /object/{bucket}/{key}`
with `x-upsert: false` (create-only), download `GET /object/{bucket}/{key}`, list
`POST /object/list/{bucket}`,
delete `DELETE /object/{bucket}` with `{"prefixes": [...]}`, bucket `GET /bucket/{bucket}`.
"""

import json
import re
import time
import urllib.error
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass

from ledgerspy_demo.identity import WORKSPACE_ID
from ledgerspy_demo.settings import StorageSettings

OBJECT_KEY = re.compile(r"^workspaces/W-[0-9a-f]{32}/(snapshot-[0-9]{12}\.zip|manifest-[0-9]{12}\.json)$")
PREFIX = re.compile(r"^workspaces/(W-[0-9a-f]{32}/)?$")
MAX_LIST_PAGES = 20
LIST_PAGE = 100
MAX_JSON_BYTES = 1024 * 1024


class StorageError(Exception):
    """`kind`: "unavailable" (network, timeout, 5xx: may be retried later), "not_found", "conflict"
    (create-only key exists), "rejected" (4xx: configuration or request problem), "too_large"."""

    def __init__(self, kind: str, status: int | None = None) -> None:
        super().__init__(f"storage {kind}" + (f" (HTTP {status})" if status else ""))
        self.kind, self.status = kind, status


@dataclass(frozen=True)
class Request:
    method: str
    url: str
    headers: dict
    body: bytes | None
    timeout: float
    max_response: int


@dataclass(frozen=True)
class Response:
    status: int
    body: bytes


Transport = Callable[[Request], Response]


def urllib_transport(req: Request) -> Response:
    """The real transport (standard library only). Raises StorageError("unavailable") on network failure."""
    # the URL is always the configured https storage origin (checked in SupabaseStorage.__init__)
    r = urllib.request.Request(req.url, data=req.body, method=req.method, headers=req.headers)  # noqa: S310
    try:
        with urllib.request.urlopen(r, timeout=req.timeout) as resp:  # noqa: S310 — https origin from settings
            body = resp.read(req.max_response + 1)
            status = resp.status
    except urllib.error.HTTPError as exc:
        body = exc.read(MAX_JSON_BYTES) if exc.fp else b""
        status = exc.code
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise StorageError("unavailable") from exc
    if len(body) > req.max_response:
        raise StorageError("too_large", status)
    return Response(status, body)


def check_key(key: str) -> str:
    if not OBJECT_KEY.fullmatch(key):
        raise ValueError("not a storage key generated for a workspace")
    return key


def workspace_prefix(workspace_id: str) -> str:
    if not WORKSPACE_ID.fullmatch(workspace_id):
        raise ValueError("not a workspace ID")
    return f"workspaces/{workspace_id}/"


class SupabaseStorage:
    def __init__(
        self,
        settings: StorageSettings,
        transport: Transport = urllib_transport,
        timeout: float = 30.0,
        retries: int = 2,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        if not settings.url.startswith("https://"):
            raise ValueError("storage must be reached over https")
        self._base = settings.url.rstrip("/") + "/storage/v1"
        self._bucket = settings.bucket
        key = settings.service_key
        # current Supabase secret keys (sb_secret_...) go in `apikey` only, never as a Bearer token; a legacy
        # service_role key is a JWT and is sent in both headers.
        self._headers = (
            {"apikey": key}
            if key.startswith("sb_secret_")
            else {"Authorization": f"Bearer {key}", "apikey": key}
        )
        self._transport = transport
        self.timeout, self.retries, self._sleep = timeout, retries, sleep

    def __repr__(self) -> str:
        return f"SupabaseStorage(bucket={self._bucket!r}, key=<redacted>)"

    def _call(self, method: str, path: str, body: bytes | None, headers: dict, max_response: int) -> Response:
        req = Request(
            method, self._base + path, {**self._headers, **headers}, body, self.timeout, max_response
        )
        last: StorageError | None = None
        for attempt in range(self.retries + 1):
            try:
                resp = self._transport(req)
            except StorageError as exc:
                if exc.kind != "unavailable":
                    raise
                last = exc
            except (TimeoutError, OSError):  # any transport's network failure: unavailable, retried
                last = StorageError("unavailable")
            else:
                if resp.status < 500:
                    return resp
                last = StorageError("unavailable", resp.status)
            if attempt < self.retries:
                self._sleep(min(2.0**attempt, 8.0))
        raise last or StorageError("unavailable")

    @staticmethod
    def _raise_for(resp: Response) -> None:
        if 200 <= resp.status < 300:
            return
        text = resp.body[:2048].decode("utf-8", "replace")
        if resp.status == 404 or '"not_found"' in text.lower() or "Object not found" in text:
            raise StorageError("not_found", resp.status)
        if resp.status == 409 or (resp.status == 400 and "Duplicate" in text):
            raise StorageError("conflict", resp.status)
        raise StorageError("rejected", resp.status)

    # ------------------------------------------------------------------ operations
    def bucket_is_private(self) -> bool:
        resp = self._call("GET", f"/bucket/{self._bucket}", None, {}, MAX_JSON_BYTES)
        self._raise_for(resp)
        try:
            return json.loads(resp.body).get("public") is False
        except (ValueError, AttributeError):
            raise StorageError("rejected", resp.status) from None

    def put(self, key: str, data: bytes, content_type: str) -> None:
        """Create-only upload: an existing key is a `conflict`, never overwritten."""
        check_key(key)
        headers = {"Content-Type": content_type, "x-upsert": "false", "Cache-Control": "no-store"}
        self._raise_for(self._call("POST", f"/object/{self._bucket}/{key}", data, headers, MAX_JSON_BYTES))

    def get(self, key: str, max_bytes: int) -> bytes:
        check_key(key)
        resp = self._call("GET", f"/object/{self._bucket}/{key}", None, {}, max_bytes)
        self._raise_for(resp)
        return resp.body

    def list_objects(self, prefix: str) -> list[dict]:
        """Entries directly under `prefix` (bounded pages). Folders have no `id`."""
        if not PREFIX.fullmatch(prefix):
            raise ValueError("not a workspace storage prefix")
        out: list[dict] = []
        for page in range(MAX_LIST_PAGES):
            body = json.dumps(
                {
                    "prefix": prefix,
                    "limit": LIST_PAGE,
                    "offset": page * LIST_PAGE,
                    "sortBy": {"column": "name", "order": "asc"},
                }
            ).encode()
            resp = self._call(
                "POST",
                f"/object/list/{self._bucket}",
                body,
                {"Content-Type": "application/json"},
                MAX_JSON_BYTES,
            )
            self._raise_for(resp)
            try:
                items = json.loads(resp.body)
            except ValueError:
                raise StorageError("rejected", resp.status) from None
            if not isinstance(items, list):
                raise StorageError("rejected", resp.status)
            out.extend(i for i in items if isinstance(i, dict) and isinstance(i.get("name"), str))
            if len(items) < LIST_PAGE:
                return out
        return out

    def delete(self, keys: list[str]) -> None:
        for key in keys:
            check_key(key)
        for i in range(0, len(keys), 100):
            body = json.dumps({"prefixes": keys[i : i + 100]}).encode()
            resp = self._call(
                "DELETE",
                f"/object/{self._bucket}",
                body,
                {"Content-Type": "application/json"},
                MAX_JSON_BYTES,
            )
            self._raise_for(resp)
