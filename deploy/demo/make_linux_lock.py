"""Generate `requirements-linux.lock` for the demo container (run INSIDE the base image, see below).

The offline release's `requirements.lock` pins Windows wheels. The demo image runs on Linux, so it gets its
own lock with the SAME versions: pip resolves the runtime pins of pyproject.toml, constrained to every version
of requirements.lock, to manylinux / pure wheels, and each wheel's SHA-256 is recorded. The image installs
with `--require-hashes --no-deps --only-binary=:all:`.

    docker run --rm -v "<repo>:/src" -w /src python:3.12-slim-bookworm@sha256:<digest> \\
        python deploy/demo/make_linux_lock.py
"""

import hashlib
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "requirements-linux.lock"
HEADER = """\
# LedgerSpy PUBLIC DEMO container lock (generated by deploy/demo/make_linux_lock.py; do not edit by hand).
# The runtime pins of pyproject.toml at the versions of requirements.lock, resolved for CPython 3.12 on
# Linux x86_64, with each wheel's SHA-256. Not used by the offline release (which uses requirements.lock).
"""


def main() -> int:
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    pins = pyproject["project"]["dependencies"]
    release_lock = (ROOT / "requirements.lock").read_text(encoding="utf-8")
    same = re.findall(r"^([A-Za-z0-9_.-]+==[^\s\\]+)", release_lock, re.M)  # the release's exact versions
    with tempfile.TemporaryDirectory() as tmp:
        constraints = Path(tmp) / "constraints.txt"
        constraints.write_text("\n".join(same) + "\n", encoding="utf-8")
        wheels = Path(tmp) / "wheels"
        cmd = [sys.executable, "-m", "pip", "download", "--only-binary=:all:", "--quiet"]
        cmd += ["--dest", str(wheels), "--constraint", str(constraints), *pins]
        subprocess.run(cmd, check=True)  # noqa: S603 — this interpreter's pip, fixed arguments
        lines = []
        for whl in sorted(wheels.glob("*.whl"), key=lambda p: p.name.lower()):
            name, version = whl.name.split("-")[:2]
            name = re.sub(r"[-_.]+", "-", name).lower()
            digest = hashlib.sha256(whl.read_bytes()).hexdigest()
            lines.append(f"{name}=={version} \\\n    --hash=sha256:{digest}")
    OUT.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines)} wheels locked")
    return 0


if __name__ == "__main__":
    sys.exit(main())
