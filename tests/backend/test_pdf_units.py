CLOSE = "Closing Balance: 11,482.80"


def settings(**pdf):
    p = CFG.pdf.model_dump(mode="json")
    for k, v in pdf.items():
        if isinstance(v, dict):
            p[k] = p[k] | v
        else:
            p[k] = v
    return {
        "pdf": p,
        "date_formats": list(CFG.mapping.date_formats),
        "min_parse_rate": CFG.mapping.min_parse_rate,
    }


def run(pdf: bytes, **pdf_overrides) -> dict:
    d = Path(tempfile.mkdtemp())
    p = d / "s.pdf"
    p.write_bytes(pdf)
    return extract.run(p, settings(**pdf_overrides))


def txns(r):
    return [x for x in r["items"] if x["kind"] == "transaction"]


