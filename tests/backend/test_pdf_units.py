def _txn(**kw):
    base = {
        "fields": {"date": "02/01/2024", "debit": "1.00", "balance": "2.00"},
        "method": "text",
        "roles_present": ["balance", "credit", "date", "debit"],
        "uncertain_words": [],
        "columns_source": "page",
    }
    return base | kw


def test_review_rules():
    fm = list(CFG.mapping.date_formats)
    t = _txn()
    validate.review_row(t, fm, ".", 70, True)
    assert t["review_required"] is False and t["parse"] == {
        "date": "ok",
        "debit": "ok",
        "credit": "missing",
        "balance": "ok",
    }
    t = _txn(method="ocr", ocr_words=[{"text": "1.00", "conf": 96.0}])
    validate.review_row(t, fm, ".", 70, True)
    assert t["reasons"] == ["ocr_derived"]  # high OCR confidence still needs a reviewer
    t = _txn(method="ocr", ocr_words=[{"text": "1.0O", "conf": 41.0}])
    validate.review_row(t, fm, ".", 70, True)
    assert "low_ocr_confidence" in t["reasons"] and t["low_confidence_words"] == [
        {"text": "1.0O", "conf": 41.0}
    ]
    t = _txn(method="text_over_image", uncertain_words=["X"], replacement_chars=1, columns_source="carried")
    validate.review_row(t, fm, ".", 70, True)
    assert set(t["reasons"]) == {
        "text_layer_over_image",
        "column_assignment_uncertain",
        "unmapped_glyphs",
        "columns_carried_from_previous_page",
    }
    t = _txn()
    validate.review_row(t, fm, ".", 70, False)
    assert t["reasons"] == ["review_policy_all_rows"]


def test_decimal_separator_rule():
    rows = [{"fields": {"debit": "1.234,56"}}, {"fields": {"debit": "10,00"}}]
    assert validate.decimal_separator(rows, 0.98) == ","
    rows = [{"fields": {"debit": "1,234.56"}}, {"fields": {"debit": "10.00"}}]
    assert validate.decimal_separator(rows, 0.98) == "."
    assert validate.decimal_separator([{"fields": {"debit": "1,234"}}], 0.98) is None  # 1234 or 1.234?


def test_statement_checks_only_with_known_semantics():
    t = [_txn(item_no=1, page=1, reasons=[], review_required=False)]
    assert validate.statement_checks(t, {}, None, ".")["status"] == "not_evaluated"
    assert validate.statement_checks(t, {}, "outflow", None)["status"] == "not_evaluated"
    t2 = [_txn(item_no=1, page=1, reasons=[], fields={"date": "x", "debit": "1.00", "balance": "5.00 Cr"})]
