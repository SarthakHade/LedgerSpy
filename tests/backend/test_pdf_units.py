def test_digital_statement_rows_fields_context_and_provenance():
    r = run(B.statement_pdf(ROWS, info=INFO, closing=CLOSE))
    assert r["status"] == "completed" and [p["method"] for p in r["pages"]] == ["text"]
    t = txns(r)
    assert [x["fields"]["date"] for x in t] == ["02/01/2024", "03/01/2024", "05/01/2024"]
    assert t[0]["fields"] == {
        "date": "02/01/2024",
        "description": "NEFT DR ACME TRADERS",
        "reference": "UTR0001",
        "debit": "1,000.00",
        "balance": "9,000.00",
    }
    assert t[1]["fields"]["description"] == "RTGS CR ZED LTD INV 77 PART PAYMENT"  # continuation merged
    assert "INV 77 PART PAYMENT" in t[1]["text"] and t[1]["continuation_items"]
    assert t[0]["context"] == {"account": "1234567890", "currency": "INR"}  # stated, never assumed
    assert all(x["page"] == 1 and len(x["bbox"]) == 4 and x["method"] == "text" for x in t)
    assert all(
        not x["review_required"] and x["parse"]["debit" if "debit" in x["fields"] else "credit"] == "ok"
        for x in t
    )
    kinds = r["coverage"]["by_kind"]
    assert kinds["statement_info"] == 4 and kinds["page_footer"] == 1 and kinds["closing_balance"] == 1
    assert r["coverage"]["classified_share"] == 1.0 and r["coverage"]["lines"] == sum(kinds.values())
    s = r["statement"]
    assert s["header_semantics"] == "outflow" and s["checks"]["status"] == "evaluated"
    assert s["checks"]["checks"]["opening_matches"] and s["checks"]["checks"]["closing_matches"]
    assert s["checks"]["checks"]["opening_plus_movement_equals_closing"] is True
    assert r["engine"]["ocr"]["used"] is False and r["engine"]["pdf"]["pdfium"]


def test_reprocessing_is_deterministic_and_inputs_untouched():
    pdf = B.statement_pdf(ROWS, info=INFO, closing=CLOSE)
    a, b = run(pdf), run(pdf)
    strip = lambda r: {k: v for k, v in r.items() if k not in ("seconds", "pages")}  # noqa: E731 — timings vary
    assert strip(a) == strip(b)
    assert [{k: v for k, v in p.items() if k != "seconds"} for p in a["pages"]] == [
        {k: v for k, v in p.items() if k != "seconds"} for p in b["pages"]
    ]


