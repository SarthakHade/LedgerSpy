def test_invalid_pdfs_raise_explicit_errors():
    d = Path(tempfile.mkdtemp())
    cases = {
        "garbage.pdf": (b"%PDF-1.4 this is not a pdf", "pdf_malformed"),
        "truncated.pdf": (B.build([{"text": [(36, 40, "x")]}], garbage_trailer=True), "pdf_malformed"),
        "notpdf.pdf": (b"PK\x03\x04 zip pretending", "pdf_malformed"),
        "locked.pdf": (B.build([{"text": [(36, 40, "secret")]}], user_password="pw"), "pdf_encrypted"),
    }
    for name, (data, code) in cases.items():
        (d / name).write_bytes(data)
        with pytest.raises(pages.PdfError) as e:
            extract.run(d / name, settings())
        assert e.value.code == code, name
    many = B.build([{"text": [(36, 40, f"page {i}")]} for i in range(4)])
    (d / "many.pdf").write_bytes(many)
    with pytest.raises(pages.PdfError) as e:
        extract.run(d / "many.pdf", settings(max_pages=3))
    assert e.value.code == "pdf_too_many_pages" and e.value.details == {"pages": 4, "limit": 3}


def test_render_limit_refuses_instead_of_downscaling():
    d = Path(tempfile.mkdtemp())
    (d / "s.pdf").write_bytes(B.statement_pdf(ROWS, info=INFO))
