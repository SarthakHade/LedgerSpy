def test_text_layer_over_image_is_never_auto_accepted():
    """A page-sized image WITH a text layer (e.g. a scan someone else already OCR'd): the text is read, but
    its accuracy is unknown, so every row is review-required."""
    lines = B.statement(ROWS, info=INFO)[0]
    digital = B.build([{"text": lines, "size": 8.0}])
    w, h, data = B.render_gray(digital, 0, 72)
    r = run(B.build([{"image": (w, h, data), "text": lines, "size": 8.0}]))
    assert r["pages"][0]["method"] == "text_over_image" and r["pages"][0]["image_coverage"] >= 0.99
    assert any("accuracy unknown" in x for x in r["pages"][0]["warnings"])
    t = txns(r)
    assert len(t) == 3 and all(x["review_required"] and "text_layer_over_image" in x["reasons"] for x in t)
    assert [x["fields"]["debit" if "debit" in x["fields"] else "credit"] for x in t] == [
        "1,000.00",
        "2,500.50",
        "17.70",
    ]
    r = run(digital)
    assert r["pages"][0]["method"] == "text" and not any(x["review_required"] for x in txns(r))


