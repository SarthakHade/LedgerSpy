"""Write requirements.lock from a prepared wheelhouse (P21).

The lock lists the complete runtime closure (direct dependencies from pyproject.toml and every transitive
one), each pinned exactly and with the SHA-256 of the wheel in the wheelhouse. `pip install --require-hashes
--no-index` then installs exactly these files and nothing else.

Prepare the wheelhouse on a connected build machine (see docs/installation.md), then:

    python packaging/make_lock.py --wheelhouse <dir>

Only binary wheels for one target are supported (Windows x64, CPython 3.12 for the tested bundle).
"""

import argparse
import hashlib
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = """# LedgerSpy runtime lock (generated by packaging/make_lock.py; do not edit by hand).
# Complete runtime closure, exact versions, SHA-256 of each wheel. Target: {target}.
# Install offline: python -m pip install --no-index --find-links wheelhouse --require-hashes
#                  -r requirements.lock
"""


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def wheels(folder: Path) -> dict[str, tuple[str, str, Path]]:
    out = {}
    for whl in sorted(folder.glob("*.whl")):
        name, version = whl.name.split("-")[:2]
        if norm(name) in out:
            raise SystemExit(f"two wheels for {name} in {folder}")
        out[norm(name)] = (name.replace("_", "-"), version, whl)
    return out


def direct_pins() -> dict[str, str]:
    deps = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["dependencies"]
    return {norm(m.group(1)): m.group(2) for d in deps if (m := re.match(r"^([A-Za-z0-9_.-]+)==(\S+)", d))}


def targets(found: dict[str, tuple[str, str, Path]]) -> str:
    """The platform-specific wheel tags (python-abi-platform); pure-Python wheels run anywhere."""
    tags = set()
    for _, _, whl in found.values():
        py, abi, plat = whl.name[:-4].split("-")[-3:]
        if plat != "any":
            tags.add(f"{py}-{abi}-{plat}")
    return ", ".join(sorted(tags)) or "pure Python only"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--wheelhouse", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=ROOT / "requirements.lock")
    args = ap.parse_args(argv)
    found = wheels(args.wheelhouse)
    for name, version in direct_pins().items():
        if name not in found:
            print(f"ERROR: {name}=={version} is missing from the wheelhouse", file=sys.stderr)
            return 1
        if found[name][1] != version:
            print(f"ERROR: wheelhouse has {name} {found[name][1]}, pyproject pins {version}", file=sys.stderr)
            return 1
    lines = [HEADER.format(target=targets(found))]
    for key in sorted(found):
        name, version, whl = found[key]
        digest = hashlib.sha256(whl.read_bytes()).hexdigest()
        lines.append(f"{name}=={version} \\\n    --hash=sha256:{digest}\n")
    args.out.write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({len(found)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
